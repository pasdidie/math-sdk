"""Game-specific configuration file, inherits from src/config/config.py"""

import os
from src.config.config import Config
from src.config.distributions import Distribution
from src.config.betmode import BetMode


class GameConfig(Config):

    _instance = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
        return cls._instance

    def __init__(self):
        super().__init__()
        self.game_id = "slapstick"
        self.provider_name = "GAMBDIDIE"
        self.provider_number = 0
        self.game_name = "Slapstick"
        self.working_name = "Slapstick"
        self.wincap = 2500.0
        self.win_type = "lines"
        self.rtp = 0.9650
        self.construct_paths()

        # Game Dimensions
        self.num_reels = 3
        self.num_rows = [3] * self.num_reels
        # Board and Symbol Properties (CLAUDE.md section 4, starting values).
        self.paytable = {
            (3, "W"): 50,
            (3, "H1"): 20,
            (3, "H2"): 10,
            (3, "H3"): 5,
            (3, "L1"): 2,
            (3, "L2"): 1,
            (3, "L3"): 0.5,
        }

        # 5 fixed lines: top, middle, bottom, two diagonals.
        self.paylines = {
            1: [0, 0, 0],
            2: [1, 1, 1],
            3: [2, 2, 2],
            4: [0, 1, 2],
            5: [2, 1, 0],
        }

        self.include_padding = True
        self.special_symbols = {"wild": ["W"], "scatter": ["S"], "multiplier": ["W"]}

        # 3 scatters (one per reel max, strips are spaced) -> 8 free spins,
        # retrigger +4 during free spins.
        self.freespin_triggers = {
            self.basegame_type: {3: 8},
            self.freegame_type: {3: 4},
        }
        self.anticipation_triggers = {
            self.basegame_type: min(self.freespin_triggers[self.basegame_type].keys()) - 1,
            self.freegame_type: min(self.freespin_triggers[self.freegame_type].keys()) - 1,
        }
        # Reels (generated by tools/gen_reels.py)
        reels = {"BR0": "BR0.csv", "FR0": "FR0.csv", "WCAP": "FRWCAP.csv"}
        self.reels = {}
        for r, f in reels.items():
            self.reels[r] = self.read_reels_csv(os.path.join(self.reels_path, f))

        self.padding_reels[self.basegame_type] = self.reels["BR0"]
        self.padding_reels[self.freegame_type] = self.reels["FR0"]
        # Wild multipliers in free spins: x2/x3/x5, added on a line.
        self.padding_symbol_values = {"W": {"multiplier": {2: 100, 3: 50, 5: 20}}}

        freegame_condition = {
            "reel_weights": {
                self.basegame_type: {"BR0": 1},
                self.freegame_type: {"FR0": 1},
            },
            "scatter_triggers": {3: 1},
            "mult_values": {
                self.basegame_type: {1: 1},
                self.freegame_type: {2: 60, 3: 30, 5: 10},
            },
            "force_wincap": False,
            "force_freegame": True,
        }

        basegame_condition = {
            "reel_weights": {self.basegame_type: {"BR0": 1}},
            "mult_values": {self.basegame_type: {1: 1}},
            "force_wincap": False,
            "force_freegame": False,
        }

        wincap_condition = {
            "reel_weights": {
                self.basegame_type: {"BR0": 1},
                self.freegame_type: {"FR0": 1, "WCAP": 5},
            },
            "mult_values": {
                self.basegame_type: {1: 1},
                self.freegame_type: {3: 20, 5: 80},
            },
            "scatter_triggers": {3: 1},
            "force_wincap": True,
            "force_freegame": True,
        }

        zerowin_condition = {
            "reel_weights": {self.basegame_type: {"BR0": 1}},
            "mult_values": {
                self.basegame_type: {1: 1},
                self.freegame_type: {2: 100, 3: 50, 5: 20},
            },
            "force_wincap": False,
            "force_freegame": False,
        }

        mode_maxwins = {"base": 2500, "bonus": 2500}
        # Buy cost is a starting point, re-derived from the average bonus
        # value once the optimized run exists (docs/PAR_SHEET.md).
        bonus_cost = 55.0

        self.bet_modes = [
            BetMode(
                name="base",
                cost=1.0,
                rtp=self.rtp,
                max_win=mode_maxwins["base"],
                auto_close_disabled=False,
                is_feature=True,
                is_buybonus=False,
                distributions=[
                    Distribution(
                        criteria="wincap",
                        quota=0.001,
                        win_criteria=mode_maxwins["base"],
                        conditions=wincap_condition,
                    ),
                    Distribution(criteria="freegame", quota=0.1, conditions=freegame_condition),
                    Distribution(criteria="0", quota=0.4, win_criteria=0.0, conditions=zerowin_condition),
                    Distribution(criteria="basegame", quota=0.5, conditions=basegame_condition),
                ],
            ),
            BetMode(
                name="bonus",
                cost=bonus_cost,
                rtp=self.rtp,
                max_win=mode_maxwins["bonus"],
                auto_close_disabled=False,
                is_feature=False,
                is_buybonus=True,
                distributions=[
                    Distribution(
                        criteria="wincap",
                        quota=0.001,
                        win_criteria=mode_maxwins["bonus"],
                        conditions=wincap_condition,
                    ),
                    Distribution(criteria="freegame", quota=0.1, conditions=freegame_condition),
                ],
            ),
        ]
