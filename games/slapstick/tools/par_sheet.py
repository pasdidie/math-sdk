"""Write docs/PAR_SHEET.md from the optimized, published lookup tables
(weights = real play odds) joined with the segmented LUT (base/free split)."""
import csv
import math
from pathlib import Path

GAME = Path(__file__).resolve().parents[1]
LIB = GAME / "library"
OUT = GAME.parents[2] / "docs" / "PAR_SHEET.md"
COSTS = {"base": 1.0, "bonus": 55.0}
BUCKETS = [(0, 0), (0, 1), (1, 5), (5, 20), (20, 100), (100, 1000), (1000, 1e9)]

lines = ["# PAR SHEET — SLAPSTICK", "", "Generated by `math/games/slapstick/tools/par_sheet.py` from the optimized lookup tables (1M sims/mode).", ""]
for mode, cost in COSTS.items():
    seg = {}
    with open(LIB / "lookup_tables" / f"lookUpTableSegmented_{mode}.csv") as f:
        for sid, crit, bw, fw in csv.reader(f):
            seg[int(sid)] = (crit, float(bw), float(fw))
    rows = []
    with open(LIB / "publish_files" / f"lookUpTable_{mode}_0.csv") as f:
        for sid, w, pay in csv.reader(f):
            rows.append((int(sid), int(w), int(pay) / 100))
    tw = sum(w for _, w, _ in rows)
    mean = sum(w * p for _, w, p in rows) / tw
    rtp = mean / cost
    var = sum(w * (p - mean) ** 2 for _, w, p in rows) / tw
    hit = sum(w for _, w, p in rows if p > 0) / tw
    fs_w = sum(w for sid, w, _ in rows if seg[sid][2] > 0 or seg[sid][0] in ("freegame", "wincap"))
    base_rtp = sum(w * seg[sid][1] for sid, w, _ in rows) / tw / cost
    free_rtp = rtp - base_rtp
    maxwin = max(p for _, _, p in rows)
    maxw = sum(w for _, w, p in rows if p == maxwin) / tw
    lines += [f"## Mode `{mode}` (cost {cost:g}x)", "",
              "| Metric | Value |", "|---|---|",
              f"| RTP | {rtp * 100:.2f} % |",
              f"| Hit rate | {hit * 100:.2f} % (1 in {1 / hit:.1f}) |",
              f"| Free spins frequency | {'every round' if mode != 'base' else f'1 in {tw / fs_w:.0f}' if fs_w else '-'} |",
              f"| RTP split base / free spins | {base_rtp * 100:.1f} % / {free_rtp * 100:.1f} % |",
              f"| Volatility (std dev of win / cost) | {math.sqrt(var) / cost:.1f} |",
              f"| Max win | {maxwin:g}x bet, 1 in {1 / maxw:,.0f} |", "",
              "| Win (x bet) | Probability |", "|---|---|"]
    for lo, hi in BUCKETS:
        if hi == 0:
            pw = sum(w for _, w, p in rows if p == 0)
            label = "0"
        else:
            pw = sum(w for _, w, p in rows if lo < p <= hi) if lo > 0 else sum(w for _, w, p in rows if 0 < p <= hi)
            label = f"{lo:g}–{hi:g}" if hi < 1e9 else f"> {lo:g}"
        lines.append(f"| {label} | {pw / tw * 100:.4f} % |")
    lines.append("")
OUT.write_text("\n".join(lines) + "\n")
print("\n".join(lines))
